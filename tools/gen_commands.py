from __future__ import annotations

import asyncio
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from discord.ext import commands  # noqa: E402

from zdbf.cogs.compat import LEGACY_COMMANDS  # noqa: E402
from zdbf.core.config import Config  # noqa: E402
from zdbf.core.permissions import is_owner_only  # noqa: E402


async def main() -> None:
    import os

    from zdbf.core.bot import ZDBFBot

    with tempfile.TemporaryDirectory() as tmp:
        os.chdir(tmp)
        config = Config().load()
        config.settings.modules.cluster = False
        config.settings.modules.dashboard = True
        bot = ZDBFBot(config)
        await bot.__aenter__()
        await bot.db.connect()
        await bot.ext.load_builtin()
        legacy = {}
        for old, new in LEGACY_COMMANDS.items():
            legacy.setdefault(new, []).append(old)
        out = ["# Command reference", "",
               "Generated by `tools/gen_commands.py`. Every command works as a slash command and with the prefix",
               "(default `!`). 🔒 = bot owner only. *V1 names* still work as prefix aliases.", ""]
        by_cog: dict[str, list[commands.Command]] = {}
        for cmd in bot.walk_commands():
            if cmd.hidden or (isinstance(cmd, commands.Group) and not getattr(cmd, "fallback", None)):
                continue
            by_cog.setdefault(cmd.cog_name or "General", []).append(cmd)
        for cog_name in sorted(by_cog):
            cog = bot.get_cog(cog_name)
            out += [f"## {getattr(cog, 'emoji', '')} {cog_name}".replace("  ", " "), ""]
            if cog and cog.description:
                out += [cog.description.strip().split("\n")[0], ""]
            out += ["| Command | Description | V1 name |", "|---|---|---|"]
            for cmd in sorted(by_cog[cog_name], key=lambda c: c.qualified_name):
                sig = f" {cmd.signature}" if cmd.signature else ""
                lock = " 🔒" if is_owner_only(cmd) else ""
                desc = (cmd.description or cmd.help or "").replace("|", "\\|")
                old = ", ".join(f"`{o}`" for o in legacy.get(cmd.qualified_name, []))
                aliases = f" (aliases: {', '.join(cmd.aliases)})" if cmd.aliases else ""
                out.append(f"| `/{cmd.qualified_name}{sig}`{lock} | {desc}{aliases} | {old} |")
            out.append("")
        budget = bot.slash_command_count()
        out += [f"**{budget['top_level']}** top-level slash commands · **{budget['with_subcommands']}** including "
                "subcommands (Discord allows 100 top-level).", ""]
        (ROOT / "docs" / "guide" / "commands.md").write_text("\n".join(out), encoding="utf-8")
        print(f"wrote docs/guide/commands.md ({sum(len(v) for v in by_cog.values())} commands)")
        await bot.close()


if __name__ == "__main__":
    asyncio.run(main())
